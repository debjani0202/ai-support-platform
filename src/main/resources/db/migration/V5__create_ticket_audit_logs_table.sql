
-- Stores an audit record for important ticket actions.
CREATE TABLE ticket_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    ticket_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,

    action VARCHAR(50) NOT NULL,
    old_value TEXT,
    new_value TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_audit_logs_ticket
        FOREIGN KEY (ticket_id)
        REFERENCES tickets(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_audit_logs_actor
        FOREIGN KEY (actor_id)
        REFERENCES users(id)
);

-- Supports retrieving a ticket's history in chronological order.
CREATE INDEX idx_ticket_audit_logs_ticket_created_at
    ON ticket_audit_logs(ticket_id, created_at, id);
