-- Description: Create agent_requests table for agent access request workflow and support request notifications

CREATE TABLE agent_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    reason VARCHAR(1000),
    admin_notes VARCHAR(1000),
    rejection_reason VARCHAR(1000),
    reviewed_by BIGINT,
    reviewed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_agent_requests_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,

    CONSTRAINT fk_agent_requests_reviewer
        FOREIGN KEY (reviewed_by) REFERENCES users(id) ON DELETE SET NULL,

    CONSTRAINT chk_agent_requests_status
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),

    CONSTRAINT chk_agent_requests_rejection_reason
        CHECK (
            (status = 'REJECTED' AND rejection_reason IS NOT NULL AND length(trim(rejection_reason)) >= 5)
            OR (status != 'REJECTED' AND rejection_reason IS NULL)
        )
);

CREATE INDEX idx_agent_requests_user_id ON agent_requests(user_id);
CREATE INDEX idx_agent_requests_status ON agent_requests(status);

-- Database-enforced invariant: At most one PENDING request per user
CREATE UNIQUE INDEX uk_agent_requests_pending_per_user
    ON agent_requests(user_id)
    WHERE status = 'PENDING';

-- Expand notifications type constraint to support agent request decision notifications
ALTER TABLE notifications
    DROP CONSTRAINT chk_notifications_type,
    ADD CONSTRAINT chk_notifications_type
        CHECK (type IN (
            'TICKET_ASSIGNED',
            'TICKET_UPDATED',
            'NEW_COMMENT',
            'AGENT_REQUEST_APPROVED',
            'AGENT_REQUEST_REJECTED'
        ));
