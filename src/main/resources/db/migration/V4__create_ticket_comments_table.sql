
-- Stores replies belonging to a ticket's conversation.
CREATE TABLE ticket_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- The ticket this comment belongs to.
    ticket_id BIGINT NOT NULL,

    -- The user who wrote the comment.
    author_id BIGINT NOT NULL,

    -- The comment's actual message.
    content TEXT NOT NULL,

    -- When the comment was created.
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_ticket_comments_ticket
        FOREIGN KEY (ticket_id)
        REFERENCES tickets(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_ticket_comments_author
        FOREIGN KEY (author_id)
        REFERENCES users(id)
);

-- Speeds up retrieving a ticket's comments in chronological order.
CREATE INDEX idx_ticket_comments_ticket_created_at
    ON ticket_comments(ticket_id, created_at, id);
