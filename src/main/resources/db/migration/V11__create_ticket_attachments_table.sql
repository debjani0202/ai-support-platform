-- Stores metadata for files attached to support tickets.
-- Binary file contents are stored on the local filesystem, not in PostgreSQL.
CREATE TABLE ticket_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Parent ticket; RESTRICT aligns with V8 soft-delete/audit protection and avoids cascading orphan files on disk.
    ticket_id BIGINT NOT NULL,

    -- User who uploaded the attachment.
    uploaded_by BIGINT NOT NULL,

    -- Sanitized user-facing original filename (never used for filesystem storage).
    original_filename VARCHAR(255) NOT NULL,

    -- Server-generated opaque UUID-based filename used in local storage.
    stored_filename VARCHAR(255) NOT NULL,

    -- Validated canonical MIME type determined server-side.
    content_type VARCHAR(100) NOT NULL,

    -- Individual attachment size in bytes (1 byte to 10 MiB inclusive).
    file_size BIGINT NOT NULL,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_ticket_attachments_ticket
        FOREIGN KEY (ticket_id)
        REFERENCES tickets(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_ticket_attachments_uploaded_by
        FOREIGN KEY (uploaded_by)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT uk_ticket_attachments_stored_filename
        UNIQUE (stored_filename),

    CONSTRAINT chk_ticket_attachments_file_size
        CHECK (file_size > 0 AND file_size <= 10485760)
);

-- Supports deterministic chronological pagination of a ticket's attachments.
CREATE INDEX idx_ticket_attachments_ticket_created_at
    ON ticket_attachments (ticket_id, created_at, id);

