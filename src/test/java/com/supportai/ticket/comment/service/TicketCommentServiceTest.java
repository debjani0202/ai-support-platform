    @Test
    void shouldReturnCommentsInChronologicalOrder() {
        stubTicketFound();

        when(customer.getId()).thenReturn(customerId);
        when(customer.getName()).thenReturn("Test Customer");

        TicketComment firstComment = mock(TicketComment.class);
        TicketComment secondComment = mock(TicketComment.class);

        LocalDateTime firstTime =
                LocalDateTime.of(2026, 10, 30, 10, 0);

        LocalDateTime secondTime =
                LocalDateTime.of(2026, 10, 30, 11, 0);

        when(firstComment.getId()).thenReturn(1L);
        when(firstComment.getTicket()).thenReturn(ticket);
        when(firstComment.getAuthor()).thenReturn(customer);
        when(firstComment.getContent()).thenReturn("First comment");
        when(firstComment.getCreatedAt()).thenReturn(firstTime);

        when(secondComment.getId()).thenReturn(2L);
        when(secondComment.getTicket()).thenReturn(ticket);
        when(secondComment.getAuthor()).thenReturn(customer);
        when(secondComment.getContent()).thenReturn("Second comment");
        when(secondComment.getCreatedAt()).thenReturn(secondTime);

        Page<TicketComment> commentPage = new PageImpl<>(
                List.of(firstComment, secondComment),
                PageRequest.of(0, 20),
                2
        );

        when(commentRepository.findByTicketId(
                eq(ticketId),
                any(Pageable.class)
        )).thenReturn(commentPage);

        PageResponse<CommentResponse> response =
                ticketCommentService.getComments(
                        ticketId,
                        customerId,
                        Role.CUSTOMER,
                        0,
                        20
                );

        assertEquals(2, response.content().size());
        assertEquals(0, response.page());
        assertEquals(20, response.size());
        assertEquals(2L, response.totalElements());
        assertEquals(1, response.totalPages());
        assertTrue(response.first());
        assertTrue(response.last());

        assertEquals(1L, response.content().get(0).id());
        assertEquals("First comment", response.content().get(0).content());
        assertEquals(firstTime, response.content().get(0).createdAt());

        assertEquals(2L, response.content().get(1).id());
        assertEquals("Second comment", response.content().get(1).content());
        assertEquals(secondTime, response.content().get(1).createdAt());

        ArgumentCaptor<Pageable> pageableCaptor =
                ArgumentCaptor.forClass(Pageable.class);

        verify(commentRepository).findByTicketId(
                eq(ticketId),
                pageableCaptor.capture()
        );

        Pageable pageable = pageableCaptor.getValue();
        assertEquals(0, pageable.getPageNumber());
        assertEquals(20, pageable.getPageSize());

        Sort sort = pageable.getSort();
        assertNotNull(sort);
        assertEquals(
                Sort.Direction.ASC,
                sort.getOrderFor("createdAt").getDirection()
        );
        assertEquals(
                Sort.Direction.ASC,
                sort.getOrderFor("id").getDirection()
        );
    }

