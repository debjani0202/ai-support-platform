    @Test
    void customerShouldAddCommentToOwnTicket() {
        stubTicketFound();

        when(customer.getId()).thenReturn(customerId);
        when(customer.getName()).thenReturn("Test Customer");

        when(userRepository.findById(customerId))
                .thenReturn(Optional.of(customer));

        stubSavedComment();

        CreateCommentRequest request =
                new CreateCommentRequest("  Please help me.  ");

        CommentResponse response =
                ticketCommentService.addComment(
                        ticketId,
                        request,
                        customerId,
                        Role.CUSTOMER
                );

        assertEquals(1L, response.id());
        assertEquals(ticketId, response.ticketId());
        assertEquals(customerId, response.authorId());
        assertEquals("Test Customer", response.authorName());
        assertEquals("Please help me.", response.content());
        assertNotNull(response.createdAt());

        ArgumentCaptor<TicketComment> captor =
                ArgumentCaptor.forClass(TicketComment.class);

        verify(commentRepository).save(captor.capture());

        assertEquals(
                "Please help me.",
                captor.getValue().getContent()
        );
        assertSame(ticket, captor.getValue().getTicket());
        assertSame(customer, captor.getValue().getAuthor());

        verifyNoInteractions(notificationService);
    }

