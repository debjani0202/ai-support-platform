import type { TicketAuditLogResponse } from '@/types/audit.types';
import { History, Clock, ArrowRight, Shield } from 'lucide-react';
import { format, parseISO } from 'date-fns';

interface AuditTimelineProps {
  logs: TicketAuditLogResponse[];
  isLoading: boolean;
}

export function AuditTimeline({ logs, isLoading }: AuditTimelineProps) {
  if (isLoading) {
    return (
      <div className="space-y-4 animate-pulse">
        {Array.from({ length: 3 }).map((_, i) => (
          <div key={i} className="p-3.5 rounded-lg bg-slate-100 border border-slate-200/60 h-16" />
        ))}
      </div>
    );
  }

  if (logs.length === 0) {
    return (
      <div className="p-8 text-center bg-slate-50 rounded-xl border border-dashed border-slate-200 text-slate-500 space-y-2">
        <History className="w-8 h-8 mx-auto text-slate-400 stroke-1" />
        <p className="text-sm font-medium text-slate-700">No audit history found</p>
        <p className="text-xs text-slate-500">
          Audit events are automatically generated by the backend whenever ticket fields, status, or assignments change.
        </p>
      </div>
    );
  }

  const getActionBadge = (action: string) => {
    switch (action?.toUpperCase()) {
      case 'STATUS_CHANGED':
        return 'bg-amber-50 text-amber-700 border-amber-200/80';
      case 'ASSIGNED':
        return 'bg-blue-50 text-blue-700 border-blue-200/80';
      case 'CREATED':
        return 'bg-emerald-50 text-emerald-700 border-emerald-200/80';
      default:
        return 'bg-slate-100 text-slate-700 border-slate-200';
    }
  };

  return (
    <div className="relative pl-6 space-y-6 before:absolute before:left-2 before:top-2 before:bottom-2 before:w-0.5 before:bg-slate-200">
      {logs.map((log) => (
        <div key={log.id} className="relative group">
          {/* Timeline node bullet */}
          <div className="absolute -left-6 top-1.5 w-4 h-4 rounded-full bg-white border-2 border-indigo-600 shadow-xs" />

          <div className="p-3.5 bg-white rounded-lg border border-slate-200/80 shadow-xs space-y-2 text-xs">
            <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-1">
              <div className="flex items-center gap-2">
                <span
                  className={`px-2 py-0.5 rounded text-[10px] font-semibold border ${getActionBadge(
                    log.action
                  )}`}
                >
                  {log.action}
                </span>
                <span className="font-semibold text-slate-900 flex items-center gap-1">
                  <Shield className="w-3 h-3 text-slate-400" />
                  {log.actorName}
                </span>
                <span className="text-[11px] font-mono text-slate-400">
                  (Actor #{log.actorId})
                </span>
              </div>

              <div className="flex items-center gap-1 text-[11px] text-slate-400">
                <Clock className="w-3 h-3" />
                <span>{format(parseISO(log.createdAt), 'PPp')}</span>
              </div>
            </div>

            {/* Changed values display */}
            {(log.oldValue !== null || log.newValue !== null) && (
              <div className="pt-1.5 border-t border-slate-100 flex items-center gap-2 text-xs">
                {log.oldValue && (
                  <span className="px-2 py-0.5 rounded bg-slate-100 font-mono text-slate-600 line-through">
                    {log.oldValue}
                  </span>
                )}
                {log.oldValue && log.newValue && (
                  <ArrowRight className="w-3 h-3 text-slate-400 shrink-0" />
                )}
                {log.newValue && (
                  <span className="px-2 py-0.5 rounded bg-indigo-50 font-mono font-semibold text-indigo-700 border border-indigo-100">
                    {log.newValue}
                  </span>
                )}
              </div>
            )}
          </div>
        </div>
      ))}
    </div>
  );
}
