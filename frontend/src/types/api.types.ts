/**
 * Custom pagination response shape returned by TicketController.
 * Matches com.supportai.ticket.dto.PageResponse<T>
 */
export interface PageResponse<T> {
  content: T[];
  page: number; // 0-indexed
  size: number;
  totalElements: number;
  totalPages: number;
  first: boolean;
  last: boolean;
}

/**
 * @deprecated Legacy Spring Data Page serialization format.
 * All paginated endpoints now return PageResponse<T>.
 */
export interface SpringPage<T> {
  content: T[];
  totalElements: number;
  totalPages: number;
  size: number;
  number: number; // 0-indexed
  first: boolean;
  last: boolean;
}

/**
 * Error response structures generated by GlobalExceptionHandler.
 */
export interface ApiErrorResponse {
  timestamp: string;
  status: number;
  error: string;
  message?: string;
  errors?: Record<string, string>; // Validation failure map: { fieldName: errorMessage }
}

/**
 * Backend health probe response.
 * Matches com.supportai.health.HealthController
 */
export interface HealthResponse {
  status: string;
  service: string;
}
